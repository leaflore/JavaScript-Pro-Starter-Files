/**
 * 1. Check node.js installation
 * a. Run `node -v` to check the installed Node.js version.
 * b. If Node.js is not installed, download and install it from https://nodejs.org/.
 * 
 * 2. Make project folder
 * a. Create a new folder for your project.
 * b. Navigate to the project folder in the terminal.
 *
 * 3. Initialize npm
 * a. Run `npm init --y` or yes(but may be older way of doing it) to create a `package.json` file.
 * b. This will generate a `package.json` file with default settings.
 *
 * 4. Install Babel
 * a. Run `npm install --save-dev @babel/core @babel/cli @babel/preset-env --save-dev` to install Babel and its preset.
 * b. This will add Babel as a development dependency in your project.
 * 
 *      1. @babel/core: The core Babel library.
 *          Babel core is the main library that provides the functionality for transpiling JavaScript code.
 *      2. @babel/cli: Command-line interface for Babel.
 *          Babel CLI allows you to run Babel commands from the terminal.
 *      3. @babel/preset-env: Preset for compiling modern JavaScript down to ES5.
 *          This preset allows you to use the latest JavaScript features and transpile them to a version compatible with older environments.
 * 
 * 
 */